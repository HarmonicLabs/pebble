// Plutus V4 (Dijkstra) prelude types — selected with
// `targetPlutusVersion: "experimental-v4"`, under the SAME names as the
// V3 family — validated against the ACTUAL
// encodings produced by plutus-ledger-api 1.71.0.0's `toData`
// (the version the public Dijkstra-era testnet, Musashi, runs):
// the fixtures in fixtures/v4-data-encodings.json are hex-encoded CBOR
// of real `PlutusLedgerApi.V4` values (generated by a small Haskell
// program building sample contexts — see the `generator` field in the
// JSON). Each test decodes a fixture and reads it back through pebble's
// `*V4` prelude types on the CEK machine, so constructor indices and
// field order are pinned to the released library, not to a hand reading
// of its source.
//
// Since 1.69 every PRODUCT type of the V4 ledger API is a plain `List` of
// fields instead of `Constr 0 fields` (sum types keep their constructor
// indices); this also covers the products V4 shares with V3 by name
// (`TxOutRef`, `Rational`, `ProtocolVersion`, ...), which are list-encoded
// under "experimental-v4" and `Constr 0` under "v3".

const fixturesPath = path.resolve(
    __dirname,
    "fixtures/v4-data-encodings.json"
);
const hasFixtures = existsSync( fixturesPath );
const fixtures: Record<string, string> = hasFixtures
    ? JSON.parse( readFileSync( fixturesPath, "utf8" ) ).fixtures
    : {};

async function exportFn( src: string, functionName: string ): Promise<Uint8Array> {
    const ioApi = createMemoryCompilerIoApi({
        sources: new Map([ [ "main.pebble", fromUtf8( src ) ] ]),
        useConsoleAsOutput: false,
    });
    const c = new Compiler( ioApi, {
        ...testOptions,
        compilerVersion: COMPILER_VERSION,
        // the V4 family carries the SAME names as V3; this option selects it
        targetPlutusVersion: "experimental-v4",
    } as any );
    return await c.export({ entry: "main.pebble", root: "/", functionName } as any );
}

function evalWith( flat: Uint8Array, fixtureName: string ): { ok: boolean; msg?: string; logs: string[] } {
    const hexStr = fixtures[ fixtureName ];
    if( !hexStr ) throw new Error( `missing fixture '${fixtureName}'` );
    const d = dataFromCbor( fromHex( hexStr ) );
    const res = Machine.eval(
        new Application( parseUPLC( flat ).body, UPLCConst.data( d ) )
    );
    return res.result instanceof CEKError
        ? { ok: false, msg: res.result.msg, logs: res.logs }
        : { ok: true, logs: res.logs };
}

async function expectAccept( src: string, functionName: string, fixtureName: string ): Promise<void> {
    const flat = await exportFn( src, functionName );
    const r = evalWith( flat, fixtureName );
    if( !r.ok )
    throw new Error( `${functionName}(${fixtureName}) rejected: ${r.msg ?? ""}\ntraces:\n${r.logs.join( "\n" )}` );
}

